// Writes src/version.ts from package.json so the version is a plain constant
// (no runtime file access, safe for bundlers). Runs before every build and after
// `changeset version`.
import { readFileSync, writeFileSync } from 'node:fs';

const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const file = new URL('../src/version.ts', import.meta.url);
const source = `// Generated by scripts/sync-version.mjs. Do not edit.\n\n/** Version of the astro-myst package. */\nexport const VERSION = '${version}';\n`;
let current = '';
try {
  current = readFileSync(file, 'utf8');
} catch {}
if (current !== source) writeFileSync(file, source);
